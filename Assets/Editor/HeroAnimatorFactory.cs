        [MenuItem("Defenders/Animation/Build Hero Animators (Mixamo)")]
        public static void BuildAll()
        {
            foreach (var spec in Specs) Build(spec);
            AssetDatabase.SaveAssets();
            AssetDatabase.Refresh();
            Debug.Log("[HeroAnimatorFactory] BuildAll complete — Knight / Mage / Ranger / Cleric.");
        }

        private static void Build(HeroSpec spec)
        {
            AnimationClip idle    = LoadClip(IdleClip,    spec.searchRoots);
            AnimationClip walk    = LoadClip(WalkClip,    spec.searchRoots);
            AnimationClip run     = LoadClip(RunClip,     spec.searchRoots);
            AnimationClip victory = LoadClip(VictoryClip, spec.searchRoots);
            AnimationClip hit     = LoadClip(HitClip,   spec.searchRoots);
            AnimationClip death   = LoadClip(DeathClip, spec.searchRoots);
            AnimationClip block   = LoadClip(BlockClip, spec.searchRoots);
            AnimationClip cast    = LoadClip(spec.castClip, spec.searchRoots);
            if (cast == null && !string.IsNullOrEmpty(spec.castClipFallback))
            {
                cast = LoadClip(spec.castClipFallback, spec.searchRoots);
                if (cast != null)
                    Debug.LogWarning($"[HeroAnimatorFactory] {spec.slug}: cast clip '{spec.castClip}' " +
                                     $"missing — using fallback '{spec.castClipFallback}' (placeholder).");
            }

            // Idempotent: recreate the controller from scratch.
            AssetDatabase.DeleteAsset(spec.controllerPath);
            var ctrl = AnimatorController.CreateAnimatorControllerAtPath(spec.controllerPath);

            // Canonical AnimParams set (WO-284) — declared on every hero controller so
            // ActorAnimator's guarded verbs all resolve. States exist for the ones with
            // clips; the rest are declared-but-unused (a safe no-op) for future polish.
            ctrl.AddParameter("Speed",    AnimatorControllerParameterType.Float);
            ctrl.AddParameter("InCombat", AnimatorControllerParameterType.Bool);
            ctrl.AddParameter("Attack",   AnimatorControllerParameterType.Trigger);
            ctrl.AddParameter("Combo",    AnimatorControllerParameterType.Int);
            ctrl.AddParameter("Cast",     AnimatorControllerParameterType.Trigger);
            ctrl.AddParameter("WindUp",   AnimatorControllerParameterType.Trigger);
            ctrl.AddParameter("Block",    AnimatorControllerParameterType.Bool);
            ctrl.AddParameter("Hit",      AnimatorControllerParameterType.Trigger);
            ctrl.AddParameter("HitDir",   AnimatorControllerParameterType.Int);
            ctrl.AddParameter("Dead",     AnimatorControllerParameterType.Bool);
            ctrl.AddParameter("DeathDir", AnimatorControllerParameterType.Int);
            ctrl.AddParameter("Victory",  AnimatorControllerParameterType.Trigger);

            var sm = ctrl.layers[0].stateMachine;

            // ── Locomotion: a 1-D blend tree on Speed (Idle→Walk→Run) ──────────
            // HeroLocomotion feeds a scalar Speed, so a 1-D forward blend is the
            // right model (strafe clips left for a later 2-D pass).
            var locoState = sm.AddState("Locomotion");
            sm.defaultState = locoState;

            var blend = new BlendTree { name = "Locomotion", blendType = BlendTreeType.Simple1D,
                                        blendParameter = "Speed",
                                        // CRITICAL: Unity defaults useAutomaticThresholds = true, which
                                        // OVERWRITES the AddChild thresholds with auto-spaced 0/0.5/1 —
                                        // that's why walk@6/run@9 never stuck and the hero skipped walk
                                        // (Speed 0..6 vs thresholds 0/0.5/1 = always max = run). Turn it
                                        // OFF so the explicit thresholds below are honored.
                                        useAutomaticThresholds = false };
            AssetDatabase.AddObjectToAsset(blend, ctrl);
            locoState.motion = blend;
            // Null-guarded children: only add the clips that loaded. Always have at
            // least one motion so the state isn't empty.
            // Thresholds tuned to HeroLocomotion's actual feed: _moveSpeed = 6, so
            // Speed (= Velocity.magnitude) ramps 0→6. The hero has ONE move speed,
            // so 6 must land in the WALK band (else it skips walk → straight to run,
            // the "skips walk" bug). Walk centred at 6; Run only if speed exceeds ~9.
            var added = new List<float>();
            if (idle != null) { blend.AddChild(idle, 0f);  added.Add(0f); }
            if (walk != null) { blend.AddChild(walk, 6f);  added.Add(6f); }
            if (run  != null) { blend.AddChild(run,  9f);  added.Add(9f); }
            if (added.Count == 0)
                Debug.LogWarning($"[HeroAnimatorFactory] {spec.slug}: no locomotion clips found — " +
                                 "Locomotion state is empty.");

            // ── Cast — Any → Cast on the trigger, returns to Locomotion ────────
            // WO-217: snappier — state.speed bumped + tighter exit so recovery is
            // quick. The base-layer Cast is KEPT (full-body fallback / clean attack
            // when standing); the WO-218 upper-body layer overlays the same clip so
            // the hero can also swing WHILE moving.
            if (cast != null)
            {
                var castState = sm.AddState("Cast");
                castState.motion = cast;
                castState.speed  = AttackSpeed;   // WO-217: faster swing
                var toCast = sm.AddAnyStateTransition(castState);
                toCast.hasExitTime = false; toCast.duration = 0.05f;
                toCast.AddCondition(AnimatorConditionMode.If, 0f, "Cast");
                var castBack = castState.AddTransition(locoState);
                castBack.hasExitTime = true;
                castBack.exitTime = CastExitTime;  // WO-217: return earlier
                castBack.duration = CastExitDur;   // WO-217: tighter blend
            }
            else
            {
                Debug.LogWarning($"[HeroAnimatorFactory] {spec.slug}: no cast clip — " +
                                 "Cast trigger will no-op (param still declared).");
            }

            // ── Victory — Any → Victory on the trigger, returns to Locomotion ──
            if (victory != null)
            {
                var vicState = sm.AddState("Victory");
                vicState.motion = victory;
                var toVic = sm.AddAnyStateTransition(vicState);
                toVic.hasExitTime = false; toVic.duration = 0.1f;
                toVic.AddCondition(AnimatorConditionMode.If, 0f, "Victory");
                var vicBack = vicState.AddTransition(locoState);
                vicBack.hasExitTime = true; vicBack.exitTime = 0.95f; vicBack.duration = 0.15f;
            }

            // ── WO-285: Attack (melee combo) — Any → AttackN on Attack + Combo==N ──
            // Knight cycles a 3-swing combo (Combo 0/1/2); other classes get a single
            // Attack state. Mirrors the snappy Cast timing (WO-217). Casters mostly
            // route through Cast at runtime, but the state exists so PlayAttack always
            // animates. Returns to Locomotion after the swing.
            int attackStates = BuildAttackStates(ctrl, sm, locoState, spec);

            // ── WO-285: Hit reaction — Any → Hit on the Hit trigger, back to Loco ──
            if (hit != null)
            {
                var hitState = sm.AddState("Hit");
                hitState.motion = hit;
                var toHit = sm.AddAnyStateTransition(hitState);
                toHit.hasExitTime = false; toHit.duration = 0.04f;
                toHit.canTransitionToSelf = false;
                toHit.AddCondition(AnimatorConditionMode.If, 0f, "Hit");
                var hitBack = hitState.AddTransition(locoState);
                hitBack.hasExitTime = true; hitBack.exitTime = 0.7f; hitBack.duration = 0.1f;
            }

            // ── WO-285: Death — Any → Death on Dead==true (latched), Revive clears ─
            // Dead is a BOOL latch (canonical, WO-284): the death clip holds its last
            // frame and never flickers back to idle. Revive() sets Dead=false →
            // Death → Locomotion so a respawned hero animates normally again.
            if (death != null)
            {
                var deathState = sm.AddState("Death");
                deathState.motion = death;
                var toDeath = sm.AddAnyStateTransition(deathState);
                toDeath.hasExitTime = false; toDeath.duration = 0.06f;
                toDeath.canTransitionToSelf = false;
                toDeath.AddCondition(AnimatorConditionMode.If, 0f, "Dead");
                var deathBack = deathState.AddTransition(locoState);
                deathBack.hasExitTime = false; deathBack.duration = 0.12f;
                deathBack.AddCondition(AnimatorConditionMode.IfNot, 0f, "Dead");
            }

            // ── WO-285: Block — Locomotion ⇄ Block on the Block bool ───────────────
            if (block != null)
            {
                var blockState = sm.AddState("Block");
                blockState.motion = block;
                var toBlock = locoState.AddTransition(blockState);
                toBlock.hasExitTime = false; toBlock.duration = 0.1f;
                toBlock.AddCondition(AnimatorConditionMode.If, 0f, "Block");
                var blockBack = blockState.AddTransition(locoState);
                blockBack.hasExitTime = false; blockBack.duration = 0.12f;
                blockBack.AddCondition(AnimatorConditionMode.IfNot, 0f, "Block");
            }

            // ── WO-218: Upper-Body attack layer ────────────────────────────────
            // A second Override layer (weight 1) masked to arms+torso, driven by the
            // SAME "Cast"/"Attack" triggers. Base layer keeps idle/walk/run on the
            // legs; the upper layer overrides the upper body with the attack/cast clip,
            // so the hero can swing while running. Empty default state = no override
            // when not attacking (legs+arms both come from the base layer).
            if (cast != null)
                AddUpperBodyLayer(ctrl, cast);

            EditorUtility.SetDirty(ctrl);
            Debug.Log($"[HeroAnimatorFactory] {spec.slug} built — Locomotion({added.Count} clips)" +
                      $"{(cast != null ? " + Cast(+UpperBody)" : "")}{(attackStates > 0 ? $" + Attack({attackStates})" : "")}" +
                      $"{(hit != null ? " + Hit" : "")}{(death != null ? " + Death" : "")}{(block != null ? " + Block" : "")}" +
                      $"{(victory != null ? " + Victory" : "")} → {spec.controllerPath}");
        }

        /// <summary>
        /// WO-285: builds the melee Attack state(s). A single clip → one "Attack"
        /// state fired by the Attack trigger. Multiple clips (Knight combo) → one
        /// state per clip ("Attack0/1/2"), each entered when the Attack trigger fires
        /// AND Combo == that index, so PlayerAttackController cycling Combo plays a
        /// different swing each hit. Every state returns to Locomotion (snappy, WO-217).
        /// Returns the number of attack states built (0 = no clips found).
        /// </summary>
        private static int BuildAttackStates(AnimatorController ctrl, AnimatorStateMachine sm,
                                             AnimatorState locoState, HeroSpec spec)
        {
            if (spec.attackClips == null || spec.attackClips.Length == 0) return 0;

            int built = 0;
            bool combo = spec.attackClips.Length > 1;
            for (int i = 0; i < spec.attackClips.Length; i++)
            {
                var clip = LoadClip(spec.attackClips[i], spec.searchRoots);
                if (clip == null) continue;

                var state = sm.AddState(combo ? $"Attack{i}" : "Attack");
                state.motion = clip;
                state.speed  = AttackSpeed;   // WO-217: snappier swing

                var toAttack = sm.AddAnyStateTransition(state);
                toAttack.hasExitTime = false; toAttack.duration = 0.05f;
                toAttack.canTransitionToSelf = false;
                toAttack.AddCondition(AnimatorConditionMode.If, 0f, "Attack");
                if (combo)
                    toAttack.AddCondition(AnimatorConditionMode.Equals, i, "Combo");

                var back = state.AddTransition(locoState);
                back.hasExitTime = true; back.exitTime = CastExitTime; back.duration = CastExitDur;
                built++;
            }
            return built;
        }

        /// <summary>
        /// WO-218: adds an "Upper Body" Override layer (weight 1) masked to arms +
        /// torso so the hero can attack while moving. Layer holds an empty default
        /// state (Empty) and a Cast state with the attack clip; Any→Cast on the same
        /// "Cast" trigger, then back to Empty. While not casting the upper layer sits
        /// on the empty state and contributes nothing (legs+arms = base layer).
        /// </summary>
        private static void AddUpperBodyLayer(AnimatorController ctrl, AnimationClip cast)
        {
            var mask = EnsureUpperBodyMask();

            var sm = new AnimatorStateMachine { name = "Upper Body" };
            AssetDatabase.AddObjectToAsset(sm, ctrl);

            // Empty default — no override unless an attack is in progress.
            var empty = sm.AddState("Empty");
            sm.defaultState = empty;

            // Upper-body attack state — same clip, same snappy speed (WO-217).
            var upperCast = sm.AddState("CastUpper");
            upperCast.motion = cast;
            upperCast.speed  = AttackSpeed;

            var toCast = sm.AddAnyStateTransition(upperCast);
            toCast.hasExitTime = false; toCast.duration = 0.05f;
            toCast.canTransitionToSelf = false;
            toCast.AddCondition(AnimatorConditionMode.If, 0f, "Cast");

            // WO-285: the same overlay also fires on the melee Attack trigger, so a
            // Knight swing plays on the upper body while the legs keep walking/running.
            var toAttack = sm.AddAnyStateTransition(upperCast);
            toAttack.hasExitTime = false; toAttack.duration = 0.05f;
            toAttack.canTransitionToSelf = false;
            toAttack.AddCondition(AnimatorConditionMode.If, 0f, "Attack");

            var back = upperCast.AddTransition(empty);
            back.hasExitTime = true;
            back.exitTime = CastExitTime;
            back.duration = CastExitDur;

            var layer = new AnimatorControllerLayer
            {
                name             = "Upper Body",
                stateMachine     = sm,
                defaultWeight    = 1f,
                blendingMode     = AnimatorLayerBlendingMode.Override,
                avatarMask       = mask,
            };
            ctrl.AddLayer(layer);
        }

        /// <summary>
        /// WO-218: creates (or rebuilds) the arms+torso AvatarMask asset. Enables
        /// every humanoid body part, then DISABLES the legs + root so the upper-body
        /// layer never fights the base layer's locomotion. Idempotent — overwrites
        /// the asset at <see cref="UpperMaskPath"/>.
        /// </summary>
        private static AvatarMask EnsureUpperBodyMask()
        {
            var mask = new AvatarMask();
            // Enable everything first…
            for (int i = 0; i < (int)AvatarMaskBodyPart.LastBodyPart; i++)
                mask.SetHumanoidBodyPartActive((AvatarMaskBodyPart)i, true);
            // …then turn off legs + root so they stay driven by the base (locomotion) layer.
            mask.SetHumanoidBodyPartActive(AvatarMaskBodyPart.Root,      false);
            mask.SetHumanoidBodyPartActive(AvatarMaskBodyPart.LeftLeg,   false);
            mask.SetHumanoidBodyPartActive(AvatarMaskBodyPart.RightLeg,  false);
            mask.SetHumanoidBodyPartActive(AvatarMaskBodyPart.LeftFootIK,  false);
            mask.SetHumanoidBodyPartActive(AvatarMaskBodyPart.RightFootIK, false);

            AssetDatabase.DeleteAsset(UpperMaskPath);
            AssetDatabase.CreateAsset(mask, UpperMaskPath);
            return mask;
        }

        /// <summary>Load the motion AnimationClip from an Assets/Action FBX by basename.
        /// Skips __preview__ AND bind/T-pose clips (iClone8 exports like simple_walk
        /// ship a "0_T-Pose" take alongside the real "…TempMotion" walk — we want the
        /// motion, not the bind pose). Null + warn if absent.</summary>
        private static AnimationClip LoadClip(string fbxBaseName, string[] searchRoots = null)
        {
            // WO-283: search the per-type roots in order (type folder first, then
            // Shared/), falling back to the legacy flat Assets/Action/ for old clips.
            object[] assets = null;
            string path = null;
            var roots = new List<string>();
            if (searchRoots != null) roots.AddRange(searchRoots);
            roots.Add(ActionDir);
            foreach (var root in roots)
            {
                string candidate = root + fbxBaseName + ".fbx";
                var found = AssetDatabase.LoadAllAssetsAtPath(candidate);
                if (found != null && found.Length > 0) { assets = found; path = candidate; break; }
            }
            if (assets == null || assets.Length == 0)
            {
                Debug.LogWarning($"[HeroAnimatorFactory] clip FBX not found: {fbxBaseName} " +
                                 $"(searched {string.Join(", ", roots)})");
                return null;
            }
            AnimationClip fallback = null;
            foreach (var a in assets)
            {
                if (!(a is AnimationClip clip)) continue;
                if (clip.name.StartsWith("__preview__")) continue;
                string n = clip.name.ToLowerInvariant();
                // Skip bind/T-pose takes (iClone8 "0_T-Pose"); keep the first as a
                // fallback in case the FBX has only one usable clip.
                if (n.Contains("t-pose") || n.Contains("tpose") || n.Contains("bind"))
                {
                    fallback ??= clip;
                    continue;
                }
                return clip;   // the real motion take
            }
            if (fallback != null)
                Debug.LogWarning($"[HeroAnimatorFactory] {path}: only a T-pose/bind clip found — using it.");
            else
                Debug.LogWarning($"[HeroAnimatorFactory] no motion AnimationClip inside {path}");
            return fallback;
        }
    }
