// =============================================================================
// HeroAnimatorFactory — builds per-class hero AnimatorControllers from the
// Mixamo clips in Assets/Action/ (WO-140). Replaces the obsolete Tripo-era
// HeroAnimatorSetup (which scraped 2 generic NLA takes per FBX).
// -----------------------------------------------------------------------------
// Data-driven: ONE Build(HeroSpec) algorithm consumes a per-class spec, so the
// three heroes are three spec literals (not three code paths) — refactor-ready
// toward a shared AnimatorBuildSpec when the catalog grows (NOT a meta-factory;
// see WO-140). NOT recursive: a controller is a flat state list + a blend tree.
//
// Runtime contract (verified in HeroLocomotion/HeroAbilities, 2026-05-30):
//   Speed   (float)   — HeroLocomotion sets = velocity magnitude → Idle/Walk/Run
//   Cast    (trigger) — HeroAbilities.TryCast → the class attack
//   Victory (trigger) — HeroLocomotion on wave clear → victory pose
// Controllers load via Resources.Load("Heroes/<slug>") where slug ∈
// {Knight, Ranger, Mage}; output paths are fixed at Resources/Heroes/<slug>.controller.
//
// Clips are Humanoid (Assets/Action are animationType 3 + CreateFromThisModel),
// so one clip retargets onto every hero. Every clip lookup is null-guarded — a
// missing FBX logs a warning and skips that state; the build still completes.
// =============================================================================
using System.Collections.Generic;
using UnityEditor;
using UnityEditor.Animations;
using UnityEngine;

namespace DeNelle.Editor
{
    public static class HeroAnimatorFactory
    {
        // WO-283: clips now live in per-type subfolders under Assets/Action/. Each
        // hero searches its type folder first, then Shared/ (the base set every model
        // retargets). ActionDir kept for the legacy flat-folder fallback.
        private const string ActionDir = "Assets/Action/";
        private const string SharedDir = "Assets/Action/Shared/";

        // ── WO-217 / WO-218 tuning ───────────────────────────────────────────
        // Attack/cast snappiness (WO-217): play the swing faster + recover quick.
        private const float AttackSpeed  = 1.3f;   // cast-state speed multiplier (1.2–1.35)
        private const float CastExitTime = 0.75f;  // return earlier than the old 0.9
        private const float CastExitDur  = 0.06f;  // tighter blend back to locomotion
        // Upper-body attack layer (WO-218): lets the hero swing/cast while moving.
        // Mask generated by EnsureUpperBodyMask(); arms+torso enabled, legs+root off.
        private const string UpperMaskPath = "Assets/Generated/Animators/HeroUpperBody.mask";

        // Shared locomotion clips (all classes) — canonical WO-283 Shared/ basenames.
        private const string IdleClip      = "Shared_Idle";
        private const string WalkClip      = "Shared_Walk_Forward";
        private const string RunClip       = "Shared_Run_Forward";
        private const string VictoryClip   = "Shared_Victory_Pose";

        // WO-284/285 shared combat clips — every hero retargets these from Shared/.
        private const string HitClip       = "Shared_Hit_Reaction";
        private const string DeathClip     = "Shared_Death";
        private const string BlockClip     = "Shared_Block";

        private struct HeroSpec
        {
            public string slug;            // Knight | Ranger | Mage | Cleric
            public string controllerPath;  // Resources/Heroes/<slug>.controller
            public string castClip;        // per-class spell/cast clip basename
            public string castClipFallback;// used + warned if the primary is absent
            public string[] attackClips;   // WO-285: melee combo (Knight = 3, else 1)
            public string[] searchRoots;   // WO-283: type folder first, then Shared/
        }

        // WO-283 §1 type->folder mapping. Casters (Mage + Cleric) share the Wizard set.
        private static readonly string[] KnightRoots = { "Assets/Action/Knight/",  SharedDir };
        private static readonly string[] RangerRoots = { "Assets/Action/Ranger/",  SharedDir };
        private static readonly string[] WizardRoots = { "Assets/Action/Wizard/",  SharedDir };

