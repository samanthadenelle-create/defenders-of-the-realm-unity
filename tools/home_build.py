SOUND_PAGE = os.path.join(REF_DIR, "SOUND_ORGANIZATION.md")

STAMP = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
GEN_BANNER = ("> **GENERATED by `tools/home_build.py` on {stamp} - DO NOT HAND-EDIT.** "
              "This registry is rebuilt from the actual tree on every run "
              "(`python tools/home_build.py`); a hand edit is destroyed by the next run. "
              "Every fact below carries the source path it was read from this run.")


# ── shared harvesting helpers ─────────────────────────────────────────────────

def read_text(relpath, limit=20000):
    try:
        with open(os.path.join(ROOT, relpath), encoding="utf-8", errors="replace") as f:
            return f.read(limit)
    except OSError:
        return ""

def first_heading(relpath):
    """Harvest a file's first markdown heading (or first non-blank line) - a TITLE,
    never a copied body. Returns '' when unreadable."""
    text = read_text(relpath, 4000)
    m = re.search(r"^#\s+(.+)$", text, re.MULTILINE)
    if m:
        return re.sub(r"[*`]", "", m.group(1)).strip()
    for line in text.splitlines():
        line = line.strip()
        if line and not line.startswith((">", "<", "|", "-", "```")):
            return re.sub(r"[*`#]", "", line).strip()[:140]
    return ""

def newest_ground_truth():
    """Resolve the CURRENT canon anchor NEWEST-BY-DATE at generation time (never a
    hardcoded filename - the stale-copy lesson). Root-level only; archived ones are frozen."""
    best, best_date = None, ""
    for p in glob.glob(os.path.join(ROOT, "CANON_GROUND_TRUTH_*.md")):
        m = re.search(r"CANON_GROUND_TRUTH_(\d{4}-\d{2}-\d{2})\.md$", os.path.basename(p))
        if m and m.group(1) > best_date:
            best_date, best = m.group(1), os.path.basename(p)
    return best, best_date

def walk_counts(relpath):
    """Non-.meta file count + per-extension Counter for a folder subtree (walked this run)."""
    base = os.path.join(ROOT, relpath)
    exts = Counter()
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames.sort()
        for fn in sorted(filenames):
            if fn.endswith(".meta"):
                continue
            ext = os.path.splitext(fn)[1].lower() or "(none)"
            exts[ext] += 1
    return sum(exts.values()), exts

def fmt_exts(exts):
    return ", ".join(f"{e} x{n}" for e, n in sorted(exts.items(), key=lambda kv: (-kv[1], kv[0])))


