# ── main ──────────────────────────────────────────────────────────────────────

def main():
    # 1. The two generated asset-organization registries FIRST (HOME links them).
    os.makedirs(REF_DIR, exist_ok=True)
    vfx_md, vfx_folders, vfx_files = build_vfx_page()
    with open(VFX_PAGE, "w", encoding="utf-8") as f:
        f.write(vfx_md)
    sound_md, n_sfx, n_music = build_sound_page()
    with open(SOUND_PAGE, "w", encoding="utf-8") as f:
        f.write(sound_md)

    # 2. Sections, then the dead-link gate BEFORE writing HOME.html.
    sections = build_sections()
    missing = check_links(sections)
    if missing:
        print(f"HOME_BUILD_FAIL {len(missing)} dead link(s) - a linked target does not exist on disk:")
        for m in missing:
            print(f"    MISSING {m}")
        return 1

    with open(OUT, "w", encoding="utf-8") as f:
        f.write(build_home_html(sections))

    n_links = sum(len(entries) for _, _, _, entries in sections)
    per = " ".join(f"{sid}:{len(entries)}" for _, sid, _, entries in sections)
    print(f"HOME.html written: {n_links} links, all live ({per}) + VFX_ORGANIZATION.md "
          f"({vfx_folders} folders, {vfx_files} files) + SOUND_ORGANIZATION.md "
          f"({n_sfx} SfxId, {n_music} MusicTrack values)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
