def parse_enum(relpath, name):
    """Enum member names read from the actual C# source (never from a doc)."""
    text = read_text(relpath, 60000)
    m = re.search(r"enum\s+" + re.escape(name) + r"\s*\{", text)
    if not m:
        return []
    depth, i = 1, m.end()
    start = i
    while i < len(text) and depth:
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
        i += 1
    body = text[start:i - 1]
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    body = re.sub(r"//[^\n]*", "", body)
    body = re.sub(r"\[[^\]]*\]", "", body)
    vals = []
    for part in body.split(","):
        mm = re.match(r"\s*([A-Za-z_]\w*)", part)
        if mm:
            vals.append(mm.group(1))
    return vals


def find_sources(filename):
    """Locate ALL .cs sources of this name under Assets/_Modules by walk (the CLAUDE.md
    §5 table is a convenience subset and has mis-stated homes before - the tree is the
    authority; MusicTrack.cs genuinely exists TWICE, in Core and in Audio)."""
    base = os.path.join(ROOT, "Assets", "_Modules")
    hits = []
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames.sort()
        if filename in filenames:
            hits.append(os.path.relpath(os.path.join(dirpath, filename), ROOT).replace(os.sep, "/"))
    return sorted(hits)


def parse_namespace(relpath):
    m = re.search(r"^\s*namespace\s+([\w.]+)", read_text(relpath, 8000), re.MULTILINE)
    return m.group(1) if m else "?"


def build_sound_page():
    """docs/reference/SOUND_ORGANIZATION.md - how the sounds are organized: enums read
    from the C# source, clip homes read from disk, all source-cited."""
    lines = ["# Sound Organization - generated registry (WO-943)", "",
             GEN_BANNER.format(stamp=STAMP), ""]

    sfx_srcs = find_sources("SfxId.cs")
    music_srcs = find_sources("MusicTrack.cs")
    lib_srcs = find_sources("SfxClipLibrary.cs")
    lib_src = lib_srcs[0] if lib_srcs else None
    sfx_src = sfx_srcs[0] if sfx_srcs else None
    sfx_vals = parse_enum(sfx_src, "SfxId") if sfx_src else []

    lines += [f"## `SfxId` - {len(sfx_vals)} named SFX events",
              "",
              f"Source: enum parsed from `{sfx_src or 'NOT FOUND under Assets/_Modules'}` "
              f"(namespace `{parse_namespace(sfx_src) if sfx_src else '?'}`) this run. "
              "The key to `AudioService.PlaySfxAtPosition` and `VFXManager.VfxToSfx()`.",
              ""]
    lines += [f"- `{v}`" for v in sfx_vals]

    # MusicTrack genuinely exists as TWO DISTINCT ENUMS (verified from the tree this run):
    # DeNelle.Core.Audio.MusicTrack (the cross-module key) and DeNelle.Audio.MusicTrack
    # (the mix-registry enum). A registry that silently picked one would be the exact
    # duplicated-state lie this page exists to prevent - list both, namespace-cited.
    n_music_total = 0
    lines += ["", f"## `MusicTrack` - {len(music_srcs)} enum(s) of this name in the tree", ""]
    if not music_srcs:
        lines.append("NOT FOUND under `Assets/_Modules` this run.")
    for src in music_srcs:
        vals = parse_enum(src, "MusicTrack")
        n_music_total += len(vals)
        lines += [f"### `{parse_namespace(src)}.MusicTrack` - {len(vals)} values",
                  "",
                  f"Source: enum parsed from `{src}` this run.",
                  ""]
        lines += [f"- `{v}`" for v in vals]
        lines.append("")

    lines += ["## `SfxClipLibrary` - the SfxId-to-AudioClip mapping",
              "",
              f"Source: `{lib_src or 'NOT FOUND under Assets/_Modules'}` (ScriptableObject; one Entry row "
              "per `SfxId`, null Clip = silent no-op at runtime). Create via "
              "`Assets > Create > Defenders/Audio/SFX Clip Library`; assigned to "
              "`AudioService._sfxLibrary`.", ""]

    lines += ["## Where clips live on disk", "",
              "Source: directory walks this run. Counts exclude `.meta` files.", "",
              "| Folder | Files | By type |", "|---|---|---|"]
    for rel in ["Assets/Audio", "Assets/Resources/Audio", "Assets/Resources/Sfx"]:
        if os.path.isdir(os.path.join(ROOT, rel)):
            n, exts = walk_counts(rel)
            lines.append(f"| `{rel}/` | {n} | {fmt_exts(exts) or '-'} |")
        else:
            lines.append(f"| `{rel}/` | - | NOT FOUND this run |")

    audio_abs = os.path.join(ROOT, "Assets", "Audio")
    if os.path.isdir(audio_abs):
        lines += ["", "### `Assets/Audio/` subfolders", ""]
        for d in sorted(os.listdir(audio_abs)):
            if os.path.isdir(os.path.join(audio_abs, d)):
                n, exts = walk_counts(f"Assets/Audio/{d}")
                lines.append(f"- `Assets/Audio/{d}/` - {n} file(s): {fmt_exts(exts) or '-'}")

    sfx_dir = os.path.join(ROOT, "Assets", "Resources", "Sfx")
    if os.path.isdir(sfx_dir):
        clips = sorted(f for f in os.listdir(sfx_dir)
                       if not f.endswith(".meta") and os.path.isfile(os.path.join(sfx_dir, f)))
        lines += ["", "### `Assets/Resources/Sfx/` clip files", ""]
        lines += [f"- `Assets/Resources/Sfx/{c}`" for c in clips]

    return "\n".join(lines) + "\n", len(sfx_vals), n_music_total


